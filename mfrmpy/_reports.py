"""Human-readable reports and disk-backed bundles of qualified public outputs."""
import hashlib
import json
import os
from pathlib import Path
import tempfile
import textwrap
import zipfile

import pandas as pd

from mfrmpy._core import basic_analysis, exports


def _plain(value):
    # Keep identifiers and notes on their own line, even if source labels contain controls.
    return "".join(char if char.isprintable() else repr(char)[1:-1] for char in str(value))


def render_text(analysis, qualified_tables):
    from . import __version__

    config = analysis.get("result", {}).get("config", {})
    lines = [
        "mfrmpy analysis report",
        "UTF-8 plain text; generated by mfrmpy, not a FACETS report or input specification.",
        f"PackageVersion: {__version__}",
        "AnalysisID: " + _plain(analysis["analysis_id"]),
        "ContentFingerprint: " + _plain(analysis["content_fingerprint"]),
        "Model: " + _plain(config.get("model", "observed-score G/D")),
        "Method: " + _plain(config.get("method", analysis.get("gd_analysis", {}).get("settings", {}).get("method", "anova"))),
    ]
    qualification_fields = ("optimizer_terminated", "identifiability_state", "run_state",
                            "supports_formal_inference", "calibration_hold_reason",
                            "calibration_hold_message", "screening_block_reason")
    if "result" in analysis:
        snapshot = basic_analysis.qualification_snapshot(analysis["result"])
        for name in qualification_fields:
            if name in snapshot and snapshot[name] != "":
                lines.append(name + ": " + _plain(snapshot[name]))
    if saved := analysis.get("qualification_at_save"):
        for name in qualification_fields:
            if name in saved and saved[name] != "":
                lines.append("Saved " + name + ": " + _plain(saved[name]))
    if "computed_outputs" in analysis:
        done = set(analysis["computed_outputs"])
        lines.append("Computed outputs: " + (", ".join(sorted(done)) or "none"))
        lines.append("Pending outputs: " + (", ".join(sorted({"measures", "agreement", "scorefile", "pca"} - done)) or "none"))
    lines.extend([
        "Scope: selected retained tables only; no estimation or diagnostics are run by this export.",
        "Read each table's notes and status fields. Missing/withheld values are not zero.",
        "For resuming analysis, save a separate .mfrm project. This report cannot restore a fit.",
    ])
    for index, (title, frame, note) in enumerate(qualified_tables, 1):
        lines.extend(["", "=" * 78, f"{index}. {_plain(title)} ({len(frame)} rows)", "=" * 78])
        # Explicitly disable pandas' display truncation, including long reasons and identifiers.
        printable = frame.map(_plain)
        printable.columns = [_plain(column) for column in frame.columns]
        if frame.empty:
            lines.append("(No rows)")
        elif len(frame) == 1:
            lines.extend(f"{column}: {value}" for column, value in zip(printable.columns, printable.iloc[0]))
        else:
            printable.index = pd.RangeIndex(1, len(printable) + 1, name="Row")
            lines.append(printable.to_string(index=True, max_rows=None, max_cols=None, max_colwidth=None, line_width=120))
        lines.extend(["", textwrap.fill("Note: " + _plain(note), width=120,
                                        break_long_words=False, break_on_hyphens=False)])
    if not qualified_tables:
        lines.extend(["", "No retained tables match the selection. Run diagnose() explicitly if needed."])
    return "\n".join(lines) + "\n"


def write_bundle(analysis, path, *, kind, plots):
    from . import __version__, _export_csv, plot, tables

    qualified_tables = tables(analysis, kind)
    if plots is None:
        from mfrmpy._core.desktop_outputs import figure_choices
        requests = [options for _, options in figure_choices(analysis)]
    else:
        if isinstance(plots, (str, dict)):
            raise ValueError("plots must be a list of plot kinds/options, or [] for no figures")
        requests = []
        for request in plots:
            options = {"kind": request} if isinstance(request, str) else dict(request)
            if not isinstance(options.get("kind"), str) or not options["kind"].strip():
                raise ValueError("Each plot requires a nonblank kind")
            requests.append(options)

    path = Path(path)
    # Stage alongside the target for atomic replacement; retain the old ZIP on any failure.
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=path.parent, prefix=".mfrmpy-report-") as temporary:
        staging = Path(temporary)
        report = staging / "report.out"
        report.write_bytes(render_text(analysis, qualified_tables).encode("utf-8"))
        csv_paths = _export_csv(analysis, staging / "csv", qualified_tables) if qualified_tables else []
        if csv_paths:
            manifest = pd.read_csv(csv_paths[0], keep_default_na=False)
            manifest["File"] = manifest["File"].map(lambda value: Path(value).name)
            manifest.to_csv(csv_paths[0], index=False)

        records = []
        archive_path = staging / "report.zip"
        with zipfile.ZipFile(archive_path, "w", compression=zipfile.ZIP_DEFLATED) as archive:
            def add(source, name, **metadata):
                with source.open("rb") as stream:
                    digest = hashlib.file_digest(stream, "sha256").hexdigest()
                archive.write(source, name)
                records.append(dict(File=name, SHA256=digest, **metadata))

            add(report, "report.out", Type="text")
            for source in csv_paths:
                add(source, "tables/" + source.name, Type="csv")
            for index, options in enumerate(requests, 1):
                figure = plot(analysis, **options)
                try:
                    stem = f"{index:02d}_" + exports.safe_export_name(options["kind"], max_len=48)
                    for extension in ("png", "svg"):
                        target = staging / (stem + "." + extension)
                        figure.savefig(target, format=extension, dpi=180,
                                       metadata={"Date": None} if extension == "svg" else None)
                        add(target, "plots/" + target.name, Type="figure", Options=options,
                            Caption=getattr(figure, "_mfrm_caption", {}))
                        target.unlink()
                finally:
                    figure.clear()
            manifest = dict(
                PackageVersion=__version__, AnalysisID=analysis["analysis_id"],
                ContentFingerprint=analysis["content_fingerprint"], Files=records,
                Scope="Qualified reporting outputs; no .mfrm project. Plot options and captions describe each figure's scope.",
            )
            archive.writestr("manifest.json", json.dumps(manifest, ensure_ascii=False, indent=2))
        # Windows requires a writable descriptor for fsync.
        with archive_path.open("r+b") as stream:
            os.fsync(stream.fileno())
        os.replace(archive_path, path)
    return path
